"""
Explainability Service

Generates human-readable explanations for internship recommendations
using the recommendation scores, skill gaps, and preference information.
"""


# Recommendation component weights
WEIGHTS = {
    "skill_match": 0.45,
    "academic_match": 0.25,
    "preference_match": 0.15,
    "semantic_similarity": 0.15
}


def generate_recommendation_explanation(recommendation):
    """
    Generate an explanation for an internship recommendation.

    Parameters:
        recommendation (dict): Recommendation generated by
                               get_student_recommendations().

    Returns:
        dict: Detailed explanation of the recommendation score,
              contributing factors, strengths, and skill gaps.
    """

    if not isinstance(recommendation, dict):
        raise ValueError("Recommendation must be a dictionary.")

    required_fields = [
        "internship_id",
        "title",
        "company",
        "match_score",
        "breakdown",
        "missing_skills"
    ]

    for field in required_fields:
        if field not in recommendation:
            raise ValueError(
                f"Missing required recommendation field: {field}"
            )

    breakdown = recommendation["breakdown"]

    if not isinstance(breakdown, dict):
        raise ValueError("Recommendation breakdown must be a dictionary.")

    # Extract individual scores
    skill_match = float(breakdown.get("skill_match", 0))
    academic_match = float(breakdown.get("academic_match", 0))
    preference_match = float(breakdown.get("preference_match", 0))
    semantic_similarity = float(
        breakdown.get("semantic_similarity", 0)
    )

    overall_score = float(recommendation["match_score"])

    # Calculate each component's contribution
    contributions = {
        "skill_match": round(
            skill_match * WEIGHTS["skill_match"], 2
        ),
        "academic_match": round(
            academic_match * WEIGHTS["academic_match"], 2
        ),
        "preference_match": round(
            preference_match * WEIGHTS["preference_match"], 2
        ),
        "semantic_similarity": round(
            semantic_similarity * WEIGHTS["semantic_similarity"], 2
        )
    }

    # Identify strengths
    strengths = []

    if skill_match >= 75:
        strengths.append(
            "Strong compatibility with the internship's required skills."
        )
    elif skill_match >= 50:
        strengths.append(
            "Moderate compatibility with the required skills."
        )
    else:
        strengths.append(
            "There is room to improve compatibility with the required skills."
        )

    if academic_match >= 75:
        strengths.append(
            "The student satisfies the academic eligibility requirements."
        )

    if preference_match >= 75:
        strengths.append(
            "The internship aligns well with the student's configured preferences."
        )

    if semantic_similarity >= 75:
        strengths.append(
            "The student's profile has strong semantic similarity "
            "to the internship description."
        )

    # Process missing skills
    missing_skills = recommendation.get("missing_skills") or []

    skill_gap_details = []

    for skill in missing_skills:

        if isinstance(skill, dict):

            skill_gap_details.append({
                "skill_name": skill.get("skill_name"),
                "required_proficiency": skill.get(
                    "required_proficiency"
                ),
                "student_proficiency": skill.get(
                    "student_proficiency"
                ),
                "requirement_type": skill.get(
                    "requirement_type"
                ),
                "proficiency_gap": skill.get(
                    "proficiency_gap"
                )
            })

    if skill_gap_details:

        skill_gap_message = (
            f"There are {len(skill_gap_details)} skill gaps "
            "that the student can work on to improve their profile."
        )

    else:

        skill_gap_message = (
            "The student satisfies all identified internship skill requirements."
        )

    # Match score interpretation
    if overall_score >= 85:
        match_level = "Excellent Match"

    elif overall_score >= 70:
        match_level = "Strong Match"

    elif overall_score >= 50:
        match_level = "Moderate Match"

    else:
        match_level = "Low Match"

    # Original recommendation explanations
    original_explanations = recommendation.get(
        "explanations", []
    )

    return {
        "internship_id": recommendation["internship_id"],

        "internship_title": recommendation["title"],

        "company": recommendation["company"],

        "overall_match_score": round(overall_score, 2),

        "match_level": match_level,

        "eligibility": recommendation.get("eligible", False),

        "score_breakdown": {
            "skill_match": {
                "score": round(skill_match, 2),
                "weight": "45%",
                "contribution": contributions["skill_match"]
            },

            "academic_match": {
                "score": round(academic_match, 2),
                "weight": "25%",
                "contribution": contributions["academic_match"]
            },

            "preference_match": {
                "score": round(preference_match, 2),
                "weight": "15%",
                "contribution": contributions["preference_match"]
            },

            "semantic_similarity": {
                "score": round(semantic_similarity, 2),
                "weight": "15%",
                "contribution": contributions["semantic_similarity"]
            }
        },

        "strengths": strengths,

        "skill_gaps": skill_gap_details,

        "skill_gap_summary": skill_gap_message,

        "original_explanations": original_explanations,

        "recommendation_summary": (
            f"{recommendation['title']} at "
            f"{recommendation['company']} has an overall match "
            f"score of {round(overall_score, 2)}%, classified as "
            f"{match_level}."
        )
    }
